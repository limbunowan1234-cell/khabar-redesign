#!/usr/bin/env node
// Phase 1 export: dumps `articles` from Appwrite to a D1-ready SQL file.
// Requires APPWRITE_API_KEY (server-side key, same one already used by
// this repo's Vercel deployment for lib/newsDigest.ts etc.) — not
// available in this environment, so this hasn't been run yet. Extend the
// COLLECTIONS list below once Phase 1 is validated and it's time to
// export the rest.
//
// Usage:
//   APPWRITE_API_KEY=xxx node scripts/export-appwrite.mjs
//   -> writes ./db/seed-articles.sql
//   Then: wrangler d1 execute khabar-d1 --file=./db/seed-articles.sql

import { Client, Databases, Query } from 'node-appwrite';
import { writeFileSync } from 'node:fs';

const ENDPOINT = 'https://nyc.cloud.appwrite.io/v1';
const PROJECT = 'khabardarjeeling';
const DB_ID = 'Khabar_db';

const apiKey = process.env.APPWRITE_API_KEY;
if (!apiKey) {
  console.error('Set APPWRITE_API_KEY first (same key the Vercel deployment uses).');
  process.exit(1);
}

const client = new Client().setEndpoint(ENDPOINT).setProject(PROJECT).setKey(apiKey);
const databases = new Databases(client);

function sqlString(v) {
  if (v === null || v === undefined) return 'NULL';
  return `'${String(v).replace(/'/g, "''")}'`;
}
function sqlBool(v) {
  return v ? 1 : 0;
}

async function fetchAll(collectionId) {
  const all = [];
  let cursor;
  for (;;) {
    const queries = [Query.limit(500)];
    if (cursor) queries.push(Query.cursorAfter(cursor));
    const res = await databases.listDocuments(DB_ID, collectionId, queries);
    all.push(...res.documents);
    if (res.documents.length < 500) break;
    cursor = res.documents[res.documents.length - 1].$id;
  }
  return all;
}

async function exportArticles() {
  console.log('Fetching articles from Appwrite...');
  const docs = await fetchAll('articles');
  console.log(`Got ${docs.length} articles.`);

  const lines = [];
  const imageLines = [];

  for (const a of docs) {
    const cols = [
      sqlString(a.$id), sqlString(a.slug), sqlString(a.title), sqlString(a.sideHeader),
      sqlString(a.content), sqlString(a.genre), sqlString(a.category), sqlString(a.status || 'published'),
      sqlString(a.locationDistrict), sqlString(a.locationArea), sqlString(a.imageFileId), sqlString(a.imageCaption),
      sqlString(a.youtube_id), sqlString(a.submitterId), sqlString(a.submitterName), sqlString(a.submitterEmail),
      sqlString(a.submitterAvatar), sqlString(a.authorName), sqlString(a.authorEmail), a.views || 0,
      sqlBool(a.isBreaking), sqlBool(a.isFeatured), sqlBool(a.isContestEntry), sqlBool(a.isWeeklyPick),
      sqlBool(a.weeklyLive), sqlString(a.weeklyIssue), sqlString(a.weeklySection), a.weeklyOrder || 0,
      sqlBool(a.isWeeklyLead), sqlBool(a.isGenreFeatured), sqlBool(a.isGenrePinned), sqlBool(a.isRegionFeatured),
      sqlBool(a.isRegionPinned), sqlString(a.rejectionReason), sqlString(a.trackerData),
      sqlString(a.submittedAt), sqlString(a.publishedAt), sqlString(a.$createdAt), sqlString(a.$updatedAt),
    ];
    lines.push(`INSERT INTO articles (id, slug, title, side_header, content, genre, category, status, location_district, location_area, image_file_id, image_caption, youtube_id, submitter_id, submitter_name, submitter_email, submitter_avatar, author_name, author_email, views, is_breaking, is_featured, is_contest_entry, is_weekly_pick, weekly_live, weekly_issue, weekly_section, weekly_order, is_weekly_lead, is_genre_featured, is_genre_pinned, is_region_featured, is_region_pinned, rejection_reason, tracker_data, submitted_at, published_at, created_at, updated_at) VALUES (${cols.join(', ')});`);

    const supporting = Array.isArray(a.supportingImages) ? a.supportingImages : [];
    supporting.forEach((raw, i) => {
      try {
        const parsed = JSON.parse(raw);
        imageLines.push(`INSERT INTO article_supporting_images (article_id, file_id, caption, sort_order) VALUES (${sqlString(a.$id)}, ${sqlString(parsed.fileId)}, ${sqlString(parsed.caption)}, ${i});`);
      } catch {
        console.warn(`  Skipping unparseable supportingImages entry on article ${a.$id}`);
      }
    });
  }

  const sql = ['-- Generated by export-appwrite.mjs — DO NOT hand-edit, regenerate instead.\n', ...lines, '\n', ...imageLines, ''].join('\n');
  writeFileSync(new URL('../db/seed-articles.sql', import.meta.url), sql);
  console.log(`Wrote ${lines.length} articles + ${imageLines.length} supporting images to db/seed-articles.sql`);
}

exportArticles().catch((err) => {
  console.error('Export failed:', err);
  process.exit(1);
});
