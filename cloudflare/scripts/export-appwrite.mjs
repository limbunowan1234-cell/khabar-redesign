async function exportBhasaDiwasVotes() {
  console.log('Fetching bhasa_diwas_votes from Appwrite...');
  const all = await fetchAll('bhasa_diwas_votes');
  console.log(`Got ${all.length} votes.`);
  // Appwrite's vote route checks-then-creates (listDocuments, then
  // createDocument if nothing found) -- not atomic, so duplicate votes
  // from the same voter on the same submission are possible. D1 enforces
  // the uniqueness that check never actually guaranteed; keep the
  // earliest of each pair.
  const byPair = new Map();
  for (const v of all) {
    const key = v.submissionId + '|' + v.voterId;
    const existing = byPair.get(key);
    if (!existing || new Date(v.$createdAt) < new Date(existing.$createdAt)) byPair.set(key, v);
  }
  const docs = Array.from(byPair.values());
  const lines = docs.map((v) =>
    `INSERT INTO bhasa_diwas_votes (id, submission_id, voter_id, created_at) VALUES (${sqlString(v.$id)}, ${sqlString(v.submissionId)}, ${sqlString(v.voterId)}, ${sqlString(v.$createdAt)});`
  );
  const sql = ['-- Generated by export-appwrite.mjs — DO NOT hand-edit, regenerate instead.\n', ...lines, ''].join('\n');
  writeFileSync(new URL('../db/seed-bhasa-diwas-votes.sql', import.meta.url), sql);
  console.log(`Wrote ${lines.length} votes (${all.length - docs.length} duplicates dropped) to db/seed-bhasa-diwas-votes.sql`);
}

async function main() {
  await exportArticles();
  await exportLikes();
  await exportComments();
  await exportFollows();
  await exportBookmarks();
  await exportProfiles();
  await exportBhasaDiwasSubmissions();
  await exportBhasaDiwasVotes();
}

main().catch((err) => {
  console.error('Export failed:', err);
  process.exit(1);
});
