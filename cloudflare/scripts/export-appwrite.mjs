async function exportProfiles() {
  console.log('Fetching profiles from Appwrite...');
  const docs = await fetchAll('profiles');
  console.log(`Got ${docs.length} profiles.`);
  // user_id is PRIMARY KEY -- Appwrite has occasionally allowed duplicate
  // profile docs per user (see ProfileEditor.tsx's find-or-create race);
  // keep the most recently updated one if that ever happened.
  const byUser = new Map();
  for (const p of docs) {
    const existing = byUser.get(p.userId);
    if (!existing || new Date(p.$updatedAt) > new Date(existing.$updatedAt)) byUser.set(p.userId, p);
  }
  const deduped = Array.from(byUser.values());
  const lines = deduped.map((p) =>
    `INSERT INTO profiles (user_id, display_name, user_name, bio, avatar_url, cover_url, banner_theme, home_district, joined_at) VALUES (${sqlString(p.userId)}, ${sqlString(p.displayName)}, ${sqlString(p.userName)}, ${sqlString(p.bio)}, ${sqlString(p.avatarUrl)}, ${sqlString(p.coverUrl)}, ${sqlString(p.bannerTheme)}, ${sqlString(p.homeDistrict)}, ${sqlString(p.joinedAT || p.$createdAt)});`
  );
  const sql = ['-- Generated by export-appwrite.mjs — DO NOT hand-edit, regenerate instead.\n', ...lines, ''].join('\n');
  writeFileSync(new URL('../db/seed-profiles.sql', import.meta.url), sql);
  console.log(`Wrote ${lines.length} profiles (${docs.length - deduped.length} duplicates dropped) to db/seed-profiles.sql`);
}

